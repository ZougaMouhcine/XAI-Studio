class I18nService:
    def __init__(self):
        self.current_lang = "fr"
        self._load_preference()

    def _load_preference(self):
        pref_path = os.path.join(BASE_DIR, "config", "lang.json")
        try:
            if os.path.exists(pref_path):
                with open(pref_path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    self.current_lang = data.get("lang", "fr")
        except Exception:
            pass

    def _save_preference(self):
        pref_path = os.path.join(BASE_DIR, "config", "lang.json")
        try:
            os.makedirs(os.path.dirname(pref_path), exist_ok=True)
            with open(pref_path, "w", encoding="utf-8") as f:
                json.dump({"lang": self.current_lang}, f)
        except Exception as e:
            logger.error("Failed to save language config: %s", e)

    def set_language(self, lang_code: str):
        if lang_code in ["en", "fr"]:
            self.current_lang = lang_code
            self._save_preference()
            logger.info("Language changed to %s", lang_code)

    def toggle_language(self) -> str:
        new_lang = "en" if self.current_lang == "fr" else "fr"
        self.set_language(new_lang)
        return new_lang

    def translate(self, key: str) -> str:
        return TRANSLATIONS.get(self.current_lang, TRANSLATIONS["fr"]).get(key, key)

# Global singleton instance
i18n = I18nService()

def _(key: str) -> str:
    """Shorthand for global translation function."""
    return i18n.translate(key)

